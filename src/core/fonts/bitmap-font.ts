export function resolveFont(id?: string): BitmapFont {
  if (id && id in BITMAP_FONTS) return BITMAP_FONTS[id as BitmapFontId]
  return BITMAP_FONTS['6x10']
}

export function defaultBitmapFont(library?: ExportTarget): BitmapFontId {
  if (library === 'adafruit_gfx' || library === 'tft_espi' || library === 'arduino_gfx') return '5x7'
  return '6x10'
}

export function fontsForLibrary(library?: ExportTarget): BitmapFont[] {
  if (library === 'adafruit_gfx' || library === 'tft_espi' || library === 'arduino_gfx') {
    return [BITMAP_FONTS['5x7'], BITMAP_FONTS['5x7x2'], BITMAP_FONTS['5x7x3']]
  }
  return [BITMAP_FONTS['5x7'], BITMAP_FONTS['6x10'], BITMAP_FONTS['7x13'], BITMAP_FONTS['8x13'], BITMAP_FONTS['10x20']]
}

export function measureText(text: string, fontId?: string): { w: number; h: number } {
  const font = resolveFont(fontId)
  const chars = Math.max(1, [...text].length)
  return { w: chars * font.cellW, h: font.cellH }
}

export function fitTextNode(node: SceneNode): void {
  const size = measureText(node.text || node.name || '', node.font)
  node.w = size.w
  node.h = size.h
}

export function textBaselineY(node: Pick<SceneNode, 'y' | 'font'>): number {
  return Math.round(node.y) + resolveFont(node.font).ascent
}

export function setTextBaselineY(node: SceneNode, baseline: number): void {
  node.y = Math.round(baseline) - resolveFont(node.font).ascent
}

export function applyTextFont(node: SceneNode, fontId: string): void {
  const baseline = textBaselineY(node)
  node.font = fontId
  fitTextNode(node)
  setTextBaselineY(node, baseline)
}

export function textBounds(node: Pick<SceneNode, 'x' | 'y' | 'text' | 'name' | 'font'>): { x: number; y: number; w: number; h: number } {
  const size = measureText(node.text || node.name || '', node.font)
  return { x: Math.round(node.x), y: Math.round(node.y), w: size.w, h: size.h }
}

export function normalizeTextNodes(nodes: SceneNode[], library?: ExportTarget): void {
  const fallback = defaultBitmapFont(library)
  for (const node of nodes) {
    if (node.type === 'text') {
      if (!node.font || !(node.font in BITMAP_FONTS)) node.font = fallback
      fitTextNode(node)
    }
    if (node.children?.length) normalizeTextNodes(node.children, library)
  }
}

function blitGlyph(buffer: PixelBuffer, px: number, py: number, base: number, font: BitmapFont, rgb: number): void {
  if (font.scale > 1) {
    const scale = font.scale
    for (let col = 0; col < 5; col += 1) {
      const bits = GLCD[base + col] ?? 0
      for (let row = 0; row < 7; row += 1) {
        if (!(bits & (1 << row))) continue
        for (let sy = 0; sy < scale; sy += 1) {
          for (let sx = 0; sx < scale; sx += 1) {
            buffer.set(px + col * scale + sx, py + row * scale + sy, rgb)
          }
        }
      }
    }
    return
  }
  for (let dx = 0; dx < font.glyphW; dx += 1) {
    const col = Math.min(4, Math.floor((dx * 5) / font.glyphW))
    const bits = GLCD[base + col] ?? 0
    for (let dy = 0; dy < font.glyphH; dy += 1) {
      const row = Math.min(6, Math.floor((dy * 7) / font.glyphH))
      if (bits & (1 << row)) buffer.set(px + dx, py + dy, rgb)
    }
  }
}

export function drawBitmapText(buffer: PixelBuffer, x: number, y: number, text: string, fontId: string | undefined, rgb: number): void {
  const font = resolveFont(fontId)
  const originX = Math.round(x)
  const originY = Math.round(y)
  ;[...text].forEach((raw, index) => {
    const ch = FOLD[raw] ?? raw
    const code = ch.codePointAt(0) ?? 32
    const glyph = code < 32 || code > 126 ? 0 : code - 32
    blitGlyph(buffer, originX + index * font.cellW + font.ox, originY + font.oy, glyph * 5, font, rgb)
  })
}
